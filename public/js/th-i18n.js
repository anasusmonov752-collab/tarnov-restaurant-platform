  function vacTitle(role, shift, lang) {
    const r = D.uz['role.' + role] !== undefined && role !== 'other' ? role : 'other';
    const base = tr(lang, 'role.' + r);
    return D.uz['shiftT.' + shift] !== undefined ? base + ', ' + tr(lang, 'shiftT.' + shift) : base;
  }

